#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.11"
# dependencies = []
# ///
"""Render ~/.codex/AGENTS.override.md from the tracked global AGENTS.md and untracked work rules.

Codex reads only the first non-empty global file (`AGENTS.override.md`, then `AGENTS.md`),
so the override must contain the global instructions too. Work rules live outside git
(`~/Workspace/AGENTS.md` by default) and never reach the dotfiles repository.
"""

from __future__ import annotations

import argparse
import os
from pathlib import Path
import sys
import tempfile


HOME = Path.home()
CODEX_DIR = HOME / ".codex"
GLOBAL_AGENTS = CODEX_DIR / "AGENTS.md"
WORK_RULES = HOME / "Workspace" / "AGENTS.md"
OUTPUT = CODEX_DIR / "AGENTS.override.md"
PROJECT_DOC_MAX_BYTES = 32 * 1024
GLOBAL_BUDGET_SHARE = 0.25
HEADER = "<!-- Generated by ~/.dotfiles/scripts/render-codex-agents.py. Do not edit: edit {global_} and {work}. -->\n\n"


def read_required(path: Path) -> str:
    """Читает обязательный вход и явно сообщает о его отсутствии."""
    if not path.is_file():
        raise FileNotFoundError(f"required input not found: {path}")
    text = path.read_text(encoding="utf-8").strip()
    if not text:
        raise ValueError(f"required input is empty: {path}")
    return text


def render(global_path: Path, work_path: Path) -> str:
    """Склеивает глобальные инструкции и рабочие правила в один документ."""
    header = HEADER.format(global_=global_path, work=work_path)
    return f"{header}{read_required(global_path)}\n\n{read_required(work_path)}\n"


def write_atomic(path: Path, content: str) -> None:
    """Атомарно записывает файл рядом с целевым путем."""
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp_name = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as file_obj:
            file_obj.write(content)
        os.replace(tmp_name, path)
    except BaseException:
        Path(tmp_name).unlink(missing_ok=True)
        raise


def main() -> int:
    """Точка входа CLI."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    parser.add_argument("--global-agents", type=Path, default=GLOBAL_AGENTS)
    parser.add_argument("--work-rules", type=Path, default=WORK_RULES)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="exit 1 if the override is missing or stale")
    mode.add_argument("--remove", action="store_true", help="delete the override; Codex falls back to AGENTS.md")
    args = parser.parse_args()

    if args.remove:
        args.output.unlink(missing_ok=True)
        print(f"removed {args.output}")
        return 0

    content = render(args.global_agents.resolve(), args.work_rules)
    size = len(content.encode("utf-8"))
    budget = int(PROJECT_DOC_MAX_BYTES * GLOBAL_BUDGET_SHARE)

    if args.check:
        current = args.output.read_text(encoding="utf-8") if args.output.is_file() else None
        if current != content:
            print(f"stale or missing: {args.output}; run {Path(__file__).name}", file=sys.stderr)
            return 1
        print(f"up to date: {args.output} ({size} bytes)")
        return 0

    write_atomic(args.output, content)
    print(f"wrote {args.output} ({size} bytes of {PROJECT_DOC_MAX_BYTES} project_doc_max_bytes)")
    if size > budget:
        print(f"warning: global instructions take more than {budget} bytes and crowd out project AGENTS.md", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
